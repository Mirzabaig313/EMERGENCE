def get_creature_sprite(creature_type: str, state: str = 'idle', 
                       facing: str = 'right') -> Optional[SpriteData]:
    """
    Get a creature sprite by type and state.
    
    Args:
        creature_type: Type of creature (e.g., 'dragon', 'werewolf')
        state: Animation state ('idle', 'attack', 'damaged', 'death')
        facing: Direction facing ('right' or 'left')
    
    Returns:
        List of strings representing the sprite lines, or None if not found
    """
    if creature_type not in CREATURE_SPRITES:
        return None
    
    sprite_key = f"{state}_right" if state != 'death' else 'death'
    sprite_data = CREATURE_SPRITES[creature_type].get(sprite_key)
    
    if sprite_data is None:
        return None
    
    if facing == 'left':
        # Flip the sprite horizontally
        from .sprite_flipper import flip_sprite_horizontal
        return flip_sprite_horizontal(sprite_data)
    
    return sprite_data


def get_creature_info(creature_type: str) -> Optional[Dict]:
    """
    Get metadata about a creature sprite.
    
    Args:
        creature_type: Type of creature
    
    Returns:
        Dictionary with sprite metadata or None if not found
    """
    return CREATURE_SPRITES.get(creature_type)


def get_all_creature_types() -> List[str]:
    """Get list of all available creature types."""
    return list(CREATURE_SPRITES.keys())


def get_creatures_by_tier(tier: int) -> List[str]:
    """Get all creatures of a specific tier."""
    return [
        name for name, data in CREATURE_SPRITES.items()
        if data.get('tier') == tier
    ]


def get_creatures_by_category(category: str) -> List[str]:
    """Get all creatures of a specific category."""
    return [
        name for name, data in CREATURE_SPRITES.items()
        if data.get('category') == category
    ]
